local S = S4.NewSimulation()
S:SetLattice({0.5,0},{0,1})
S:SetNumG(1)
S:AddMaterial('Air', {1,0})
S:AddLayer('top',0,'Air')
S:AddLayer('bottom',0,'Air')
S:SetFrequency(1/0.266)
S:SetExcitationPlanewave({75,90},{0,0},{1,0})
print('TOP',S:GetPowerFlux('top',0))
print('BOTTOM',S:GetPowerFlux('bottom',0))
local forward, backward = S:GetAmplitudes('top',0)
print('AMPLITUDE',forward[1][1],forward[2][1],backward[1][1],backward[2][1])
print('FIELD_ABOVE',S:GetFields({0,0,-0.02}))
print('FIELD_BELOW',S:GetFields({0,0,0.02}))
